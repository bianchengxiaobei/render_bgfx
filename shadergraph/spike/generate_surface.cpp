#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

namespace {

constexpr const char* kDefaultOutput = "shaders/shadergraph/spike/surface.spike.sc";
constexpr const char* kSurfaceSource = R"surface(// Generated by shadergraph/spike/generate_surface.cpp. Do not edit.
#ifndef HBG_SG_SPIKE_SURFACE_SC
#define HBG_SG_SPIKE_SURFACE_SC

#include "material/surface_data_types.sc"

uniform vec4 u_sg_Tint;
uniform vec4 u_sg_Smoothness;
uniform vec4 u_sg_DebugTextures;

SAMPLER2D(s_sg_MainTex, 0);
SAMPLER2D(s_sg_Dummy1, 1);
SAMPLER2D(s_sg_Dummy2, 2);
SAMPLER2D(s_sg_Dummy3, 3);
SAMPLER2D(s_sg_Dummy4, 4);

SurfaceData hbgMakeGraphSurface(vec3 worldPos, vec3 geometricNormalWS, vec3 tangentWS,
                                vec3 bitangentWS, vec2 uv)
{
    const vec2 tiling = vec2(1.0, 1.0);
    const vec2 offset = vec2(0.0, 0.0);
    const vec2 tiledUV = uv * tiling + offset;

    const vec4 texel = texture2D(s_sg_MainTex, tiledUV);
    const vec4 dummy1 = texture2D(s_sg_Dummy1, tiledUV);
    const vec4 dummy2 = texture2D(s_sg_Dummy2, tiledUV);
    const vec4 dummy3 = texture2D(s_sg_Dummy3, tiledUV);
    const vec4 dummy4 = texture2D(s_sg_Dummy4, tiledUV);

    SurfaceData surfaceData;
    surfaceData.baseColor = texel.rgb * u_sg_Tint.rgb +
        (dummy1.rgb + dummy2.rgb + dummy3.rgb + dummy4.rgb) * (1.0e-6 * u_sg_DebugTextures.x);
    surfaceData.alpha = texel.a * u_sg_Tint.a;
    surfaceData.metallic = 0.0;
    surfaceData.perceptualRoughness = clamp(1.0 - u_sg_Smoothness.x, 0.0, 1.0);
    surfaceData.roughness = max(surfaceData.perceptualRoughness * surfaceData.perceptualRoughness, 0.001);
    surfaceData.ambientOcclusion = 1.0;
    surfaceData.materialAmbientOcclusion = 1.0;

    const vec3 normalWS = normalize(geometricNormalWS);
    vec3 tangent = tangentWS;
    if (dot(tangent, tangent) < 1.0e-8)
    {
        const vec3 hint = abs(normalWS.y) < 0.99 ? vec3(0.0, 1.0, 0.0) : vec3(1.0, 0.0, 0.0);
        tangent = normalize(cross(normalWS, hint));
    }
    surfaceData.normalWS = normalWS;
    surfaceData.geometricNormalWS = normalWS;
    surfaceData.tangentWS = normalize(tangent);
    surfaceData.emissive = vec3(0.0, 0.0, 0.0);
    surfaceData.contactShadowMask = 0.0;
    surfaceData.contactShadowFade = 0.0;
    surfaceData.lightLayerMask = 65535.0;
    return surfaceData;
}

#endif // HBG_SG_SPIKE_SURFACE_SC
)surface";

} // namespace

int main(int argc, char** argv) {
    const std::filesystem::path output = argc > 1 ? argv[1] : kDefaultOutput;
    std::error_code error;
    if (output.has_parent_path()) {
        std::filesystem::create_directories(output.parent_path(), error);
    }
    std::ofstream file(output, std::ios::binary);
    if (!file) {
        std::cerr << "failed to open '" << output.string() << "'\n";
        return 1;
    }
    file << kSurfaceSource;
    if (!file) {
        std::cerr << "failed to write '" << output.string() << "'\n";
        return 1;
    }
    std::cout << "wrote " << output.string() << "\n";
    return 0;
}
